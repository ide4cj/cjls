"""Generate the runtime SDK window from the release and nightly pins."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("modules/project_model/src/sdk_window_generated.cj")


def generate(root=ROOT):
    window = json.loads((root / ".cangjie-window").read_text())
    versions = {"LTS": window["lts"]["version"], "STS": window["sts"]["version"],
                "PIN": (root / ".cangjie-version").read_text().strip()}
    lines = ["// Generated by scripts/sdk_window_codegen.py; do not edit.",
             "package project_model", ""]
    lines.extend(f'const SDK_{channel}_VERSION = {json.dumps(version)}'
                 for channel, version in versions.items())
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    destination = ROOT / OUTPUT
    if args.check:
        if not destination.exists() or destination.read_text() != expected:
            parser.exit(1, "SDK window is stale; run python3 scripts/sdk_window_codegen.py\n")
    else:
        destination.write_text(expected)
