"""Expand macro as an editor asks for it: `cjls/expandMacro`, and the code action whose command writes the expanded
file and asks the client to show it (D103). What a call expands to is `loupe`'s tests; the file and its navigation
the handler's (C7)."""

import ast
import os
import pathlib
import shutil
import subprocess
import sys

import pytest
from lsprotocol import types
from pygls.uris import to_fs_path
from pytest_lsp import LanguageClient

from conftest import CLIENTS, capabilities, loaded

# an SDK for std's `.cjo`, which std's `@Derive` is resolved in, passed as an editor passes it
SDK = os.environ.get("CJLS_E2E_SDK") or os.environ.get("CANGJIE_HOME")

SOURCE = """\
import std.deriving.*

@Derive[Equatable]
class P {
    let x: Int64 = 0
}
"""


@pytest.mark.skipif(SDK is None, reason="no SDK (CJLS_E2E_SDK)")
@pytest.mark.parametrize("editor", CLIENTS)
async def test_expand_macro_answers_the_expansion_and_shows_the_expanded_file(server: LanguageClient, tmp_path,
                                                                              editor):
    # arrange
    file = tmp_path / "a.cj"
    file.write_text(SOURCE)

    @server.feature(types.CLIENT_REGISTER_CAPABILITY)
    def register(params: types.RegistrationParams):
        pass

    await server.initialize_session(
        types.InitializeParams(
            capabilities=capabilities(editor),
            workspace_folders=[types.WorkspaceFolder(uri=tmp_path.as_uri(), name="ws")],
            initialization_options={"cangjieHome": pathlib.Path(SDK).resolve().as_uri()},
        )
    )
    await loaded(server)
    on_call = types.Position(line=2, character=2)

    # act
    expansion = await server.protocol.send_request_async(
        "cjls/expandMacro", {"textDocument": {"uri": file.as_uri()}, "position": {"line": 2, "character": 2}}
    )
    actions = await server.text_document_code_action_async(
        types.CodeActionParams(
            text_document=types.TextDocumentIdentifier(uri=file.as_uri()),
            range=types.Range(start=on_call, end=on_call),
            context=types.CodeActionContext(diagnostics=[]),
        )
    )

    # assert: std's `@Derive`, as cjls writes it
    assert expansion.name == "@Derive"
    assert expansion.kind == "cjls"
    assert expansion.expansion.startswith("// cjls's own expansion of @Derive")
    # the declaration first, as cjc's output has it, then what `@Derive` adds after it
    assert expansion.expansion.index("class P {") < expansion.expansion.index("extend P <: Equatable<P>")
    # every body a comment, a block the editor folds (D118)
    assert "public operator func ==(other: P): Bool {\n        // body generated by @Derive\n    }" in expansion.expansion

    window = capabilities(editor).window
    if window is None or window.show_document is None or not window.show_document.support:
        assert actions is None
        await server.shutdown_session()
        return

    [action] = actions
    assert action.title == "Expand macro @Derive"
    command = action.command
    if isinstance(command, str):
        # lsprotocol reads a `CodeAction` as a `Command`, its `command` (an object) as the text Python writes of it
        command = ast.literal_eval(command)
    else:
        command = {"command": command.command, "arguments": command.arguments}
    assert command["command"] == "cjls.expandMacro"

    # act: the code action's command, as the editor runs it
    await server.workspace_execute_command_async(types.ExecuteCommandParams(command=command["command"], arguments=command["arguments"]))

    # assert: the request to show the file (pytest-lsp's client shows it) came before the command's answer, and the
    # file is there, read-only
    [params] = server.shown_documents
    path = pathlib.Path(to_fs_path(params.uri))
    assert path == tmp_path / ".cache" / "cjls" / "expanded" / "a.cj.macrocall"
    text = path.read_text(encoding="utf-8")
    assert text.startswith("// generated by cjls from a.cj")
    assert "extend P <: Equatable<P>" in text
    assert params.take_focus
    assert params.selection is not None
    if sys.platform != "win32":
        assert not os.access(path, os.W_OK)
    assert (tmp_path / ".cache" / "cjls" / ".gitignore").read_text() == "*\n"

    await server.shutdown_session()


@pytest.mark.skipif(SDK is None, reason="no SDK (CJLS_E2E_SDK)")
@pytest.mark.parametrize("native_kind", ["static", "shared"])
async def test_workspace_macro_links_transitive_native_dependency(server: LanguageClient, tmp_path, native_kind):
    # arrange
    cc, ar = shutil.which("cc"), shutil.which("ar")
    if sys.platform == "win32" or cc is None or ar is None:
        pytest.skip("requires a POSIX C compiler and archiver")
    native = tmp_path / "helper" / "native"
    native.mkdir(parents=True)
    (native / "value.c").write_text("long long native_value(void) { return 42; }\n")
    subprocess.run([cc, "-fPIC", "-c", "value.c", "-o", "value.o"], cwd=native,
                   check=True, capture_output=True, timeout=30)
    if native_kind == "static":
        command = [ar, "rcs", "libvalue.a", "value.o"]
    elif sys.platform == "darwin":
        command = [cc, "-dynamiclib", "value.o", "-o", "libvalue.dylib"]
    else:
        command = [cc, "-shared", "value.o", "-o", "libvalue.so"]
    subprocess.run(command, cwd=native, check=True, capture_output=True, timeout=30)
    (tmp_path / "cjpm.toml").write_text('''[package]
name = "app"
output-type = "executable"
[dependencies]
helper = {path = "helper", output-type = "dynamic"}
''')
    (tmp_path / "helper" / "cjpm.toml").write_text('''[package]
name = "helper"
output-type = "static"
[ffi.c]
value = {path = "native"}
''')
    helper = tmp_path / "helper" / "src"
    helper.mkdir()
    (helper / "value.cj").write_text('''package helper
import helper.gen.*
foreign func native_value(): Int64
@NativeValue public func extraValue(): Int64 { 0 }
public func value(): Int64 { unsafe { native_value() } + extraValue() - 42 }
''')
    generator = helper / "gen"
    generator.mkdir()
    (generator / "macro.cj").write_text('''macro package helper.gen
import std.ast.*
foreign func native_value(): Int64
public macro NativeValue(input: Tokens): Tokens {
    let answer = Token(INTEGER_LITERAL, unsafe { native_value() }.toString())
    quote(public func extraValue(): Int64 { $answer })
}
''')
    macros = tmp_path / "src" / "ms"
    macros.mkdir(parents=True)
    (macros / "macro.cj").write_text('''macro package app.ms
import std.ast.*
import helper.*
public macro Value(input: Tokens): Tokens {
    let answer = Token(INTEGER_LITERAL, value().toString())
    quote(public func generated(): Int64 { $answer })
}
''')
    file = tmp_path / "src" / "main.cj"
    file.write_text('''package app
import app.ms.*
@Value public func generated(): Int64 { 0 }
''')

    @server.feature(types.CLIENT_REGISTER_CAPABILITY)
    def register(params: types.RegistrationParams):
        pass

    # act
    await server.initialize_session(types.InitializeParams(
        capabilities=capabilities("visual-studio-code"),
        workspace_folders=[types.WorkspaceFolder(uri=tmp_path.as_uri(), name="ws")],
        initialization_options={"cangjieHome": pathlib.Path(SDK).resolve().as_uri()},
    ))
    await loaded(server)

    async def expansion():
        return await server.protocol.send_request_async("cjls/expandMacro", {
            "textDocument": {"uri": file.as_uri()}, "position": {"line": 2, "character": 2},
        })

    while (expanded := await expansion()) is None or expanded.kind != "server":
        await server.refreshes.get()
    # assert: the macro executed native code through its source dependency.
    assert "func generated(): Int64" in expanded.expansion
    assert "42" in expanded.expansion
    await server.shutdown_session()


@pytest.mark.skipif(SDK is None, reason="no SDK (CJLS_E2E_SDK)")
async def test_the_server_runs_stds_macro_once_the_workspace_is_loaded(server: LanguageClient, tmp_path):
    # arrange
    file = tmp_path / "a.cj"
    file.write_text(SOURCE)

    @server.feature(types.CLIENT_REGISTER_CAPABILITY)
    def register(params: types.RegistrationParams):
        pass

    await server.initialize_session(
        types.InitializeParams(
            capabilities=capabilities("visual-studio-code"),
            workspace_folders=[types.WorkspaceFolder(uri=tmp_path.as_uri(), name="ws")],
            initialization_options={"cangjieHome": pathlib.Path(SDK).resolve().as_uri()},
        )
    )
    await loaded(server)

    async def expansion():
        return await server.protocol.send_request_async(
            "cjls/expandMacro", {"textDocument": {"uri": file.as_uri()}, "position": {"line": 2, "character": 2}}
        )

    # act: asked again after every change of the files the server tells of, until the macro server's answer is set
    # (D123): only the server's own state starts the macros (D141)
    while (expanded := await expansion()).kind != "server":
        await server.refreshes.get()

    # assert
    assert expanded.name == "@Derive"
    assert "extend P <: Equatable<P>" in expanded.expansion

    await server.shutdown_session()
