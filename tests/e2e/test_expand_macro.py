"""Expand macro as an editor asks for it: `cjls/expandMacro`, and the code action whose command writes the expanded
file and asks the client to show it (D103). What a call expands to is `loupe`'s tests; the file and its navigation
the handler's (C7)."""

import ast
import os
import pathlib
import sys

import pytest
from lsprotocol import types
from pygls.uris import to_fs_path
from pytest_lsp import LanguageClient

from conftest import CLIENTS, capabilities, loaded

# an SDK for std's `.cjo`, which std's `@Derive` is resolved in, passed as an editor passes it
SDK = os.environ.get("CJLS_E2E_SDK") or os.environ.get("CANGJIE_HOME")

SOURCE = """\
import std.deriving.*

@Derive[Equatable]
class P {
    let x: Int64 = 0
}
"""


@pytest.mark.skipif(SDK is None, reason="no SDK (CJLS_E2E_SDK)")
@pytest.mark.parametrize("editor", CLIENTS)
async def test_expand_macro_answers_the_expansion_and_shows_the_expanded_file(server: LanguageClient, tmp_path,
                                                                              editor):
    # arrange
    file = tmp_path / "a.cj"
    file.write_text(SOURCE)

    @server.feature(types.CLIENT_REGISTER_CAPABILITY)
    def register(params: types.RegistrationParams):
        pass

    await server.initialize_session(
        types.InitializeParams(
            capabilities=capabilities(editor),
            workspace_folders=[types.WorkspaceFolder(uri=tmp_path.as_uri(), name="ws")],
            initialization_options={"cangjieHome": pathlib.Path(SDK).resolve().as_uri()},
        )
    )
    await loaded(server)
    on_call = types.Position(line=2, character=2)

    # act
    expansion = await server.protocol.send_request_async(
        "cjls/expandMacro", {"textDocument": {"uri": file.as_uri()}, "position": {"line": 2, "character": 2}}
    )
    actions = await server.text_document_code_action_async(
        types.CodeActionParams(
            text_document=types.TextDocumentIdentifier(uri=file.as_uri()),
            range=types.Range(start=on_call, end=on_call),
            context=types.CodeActionContext(diagnostics=[]),
        )
    )

    # assert: std's `@Derive`, as cjls writes it
    assert expansion.name == "@Derive"
    assert expansion.kind == "cjls"
    assert expansion.expansion.startswith("// cjls's own expansion of @Derive")
    # the declaration first, as cjc's output has it, then what `@Derive` adds after it
    assert expansion.expansion.index("class P {") < expansion.expansion.index("extend P <: Equatable<P>")
    assert "public operator func ==(other: P): Bool {}" in expansion.expansion

    window = capabilities(editor).window
    if window is None or window.show_document is None or not window.show_document.support:
        assert actions is None
        await server.shutdown_session()
        return

    # act: the code action's command, as the editor runs it
    [action] = actions
    assert action.title == "Expand macro @Derive"
    command = action.command
    if isinstance(command, str):
        # lsprotocol reads a `CodeAction` as a `Command`, its `command` (an object) as the text Python writes of it
        command = ast.literal_eval(command)
    else:
        command = {"command": command.command, "arguments": command.arguments}
    assert command["command"] == "cjls.expandMacro"
    await server.workspace_execute_command_async(types.ExecuteCommandParams(command=command["command"], arguments=command["arguments"]))

    # assert: the request to show the file (pytest-lsp's client shows it) came before the command's answer, and the
    # file is there, read-only
    [params] = server.shown_documents
    path = pathlib.Path(to_fs_path(params.uri))
    assert path == tmp_path / ".cache" / "cjls" / "expanded" / "a.cj.macrocall"
    text = path.read_text(encoding="utf-8")
    assert text.startswith("// generated by cjls from a.cj")
    assert "extend P <: Equatable<P>" in text
    assert params.take_focus
    assert params.selection is not None
    if sys.platform != "win32":
        assert not os.access(path, os.W_OK)
    assert (tmp_path / ".cache" / "cjls" / ".gitignore").read_text() == "*\n"

    await server.shutdown_session()
